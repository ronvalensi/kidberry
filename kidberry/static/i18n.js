let LANG = 'en';

function t(key, vars = {}) {
  const v = I18N[LANG]?.[key] ?? I18N.en[key];
  if (v == null) return key;
  if (typeof v === 'function') return Array.isArray(vars) ? v(...vars) : v(vars);
  if (typeof v !== 'string') return v;
  return v.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

